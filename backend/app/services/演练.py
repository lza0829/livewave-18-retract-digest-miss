import concurrent.futures
import itertools

from app.db import 读事务, 写事务
from app.seed import 保证房间
from app.services import 时间, 装载
from app.modules import 允许迟到策略

演练房_单修 = "房甲"
演练房_并发 = "房丙"
演练开播 = "2026-11-22T12:00:00Z"
首窗起 = "2026-11-22T12:00:00Z"
首窗止 = "2026-11-22T12:01:00Z"

_运行计数 = itertools.count(1)


def _运行号() -> int:
    """每次演练一个唯一后缀，避免装载批次编号跨轮冲突。"""
    return next(_运行计数)


def _事件(编号, 房间键, 事件时, 点赞, 送礼=0, 类型="点赞"):
    return {
        "事件编号": 编号,
        "房间键": 房间键,
        "事件类型": 类型,
        "事件时": 事件时,
        "处理时": 时间.加秒(事件时, 1),
        "观众键": f"观-{编号}",
        "点赞增量": 点赞,
        "送礼额": 送礼,
    }


def _重置房(房间键: str) -> None:
    with 写事务() as conn:
        conn.execute("DELETE FROM 互动事件 WHERE 房间键=?", (房间键,))
        conn.execute("DELETE FROM 撤回单 WHERE 房间键=?", (房间键,))
        conn.execute("DELETE FROM 热度窗 WHERE 房间键=?", (房间键,))
        conn.execute("DELETE FROM 旁路匣 WHERE 载荷 LIKE ?", (f'%"房间键": "{房间键}"%',))
        conn.execute("DELETE FROM 水位线 WHERE 房间键=?", (房间键,))
        conn.execute("DELETE FROM 直播间 WHERE 房间键=?", (房间键,))
        保证房间(conn, 房间键, 演练开播)


def _取证据(窗键: str):
    return 允许迟到策略.窗口证据(窗键)


def 跑演练() -> dict:
    结果 = {
        "口径": 允许迟到策略.口径,
        "步骤一_首窗后首次迟到": _步骤一(),
        "步骤二_第二次迟到": _步骤二(),
        "步骤三_修正与抬水位并发": _步骤三(),
        "步骤四_故障注入同成败": _附加_故障注入同成败(),
    }
    结果["全部通过"] = all(
        v.get("通过") for k, v in 结果.items() if isinstance(v, dict)
    )
    return 结果


def _步骤一() -> dict:
    房 = 演练房_单修
    _重置房(房)
    wk = 时间.窗键(房, 首窗起)

    装载.装一批(
        {
            "批次编号": f"{房}-关窗-{_运行号()}",
            "事件": [
                _事件(f"{房}-E1", 房, "2026-11-22T12:00:10Z", 3),
                _事件(f"{房}-E2", 房, "2026-11-22T12:00:40Z", 0, 50, "送礼"),
                _事件(f"{房}-E3", 房, "2026-11-22T12:01:05Z", 2),
            ],
        }
    )
    关窗前 = _取证据(wk)
    if 关窗前 is None or 关窗前["状态"] != "已关闭":
        return {"通过": False, "说明": "首窗未被关闭，无法演练迟到修正"}

    基线 = dict(关窗前["当前合计"])
    基版本 = 关窗前["版本"]

    装载.装一批(
        {"批次编号": f"{房}-迟到1-{_运行号()}", "事件": [_事件(f"{房}-L1", 房, "2026-11-22T12:00:55Z", 4)]}
    )
    首次后 = _取证据(wk)

    合计已变 = (
        首次后["当前合计"]["点赞"] == 基线["点赞"] + 4
        and 首次后["当前合计"]["送礼"] == 基线["送礼"]
        and 首次后["当前合计"]["笔数"] == 基线["笔数"] + 1
    )
    版本已升 = 首次后["版本"] == 基版本 + 1
    有撤回 = 首次后["修正次数"] == 1
    证据有效 = 首次后["valid"]
    通过 = all([合计已变, 版本已升, 有撤回, 证据有效])
    return {
        "通过": 通过,
        "房间": 房,
        "窗键": wk,
        "关闭后基线": 基线,
        "关闭后版本": 基版本,
        "允许迟到界": 首次后["允许迟到界"],
        "迟到事件时": "2026-11-22T12:00:55Z",
        "修正后合计": 首次后["当前合计"],
        "修正后版本": 首次后["版本"],
        "撤回链": 首次后["撤回链"],
        "合计必变": 合计已变,
        "版本升高": 版本已升,
        "撤回证据": 有撤回,
        "valid": 证据有效,
        "说明": [
            f"关闭发射：赞{基线['点赞']}/送{基线['送礼']}/笔{基线['笔数']}，版本{基版本}",
            f"迟到4赞后：赞{首次后['当前合计']['点赞']}/送{首次后['当前合计']['送礼']}"
            f"/笔{首次后['当前合计']['笔数']}，版本{首次后['版本']}",
            "允许迟到界内完成修正并留下撤回单",
        ]
        if 通过
        else ["迟到修正未按甲口径生效"],
    }


def _步骤二() -> dict:
    房 = 演练房_单修
    wk = 时间.窗键(房, 首窗起)
    前 = _取证据(wk)
    if 前 is None or 前["状态"] != "已关闭" or 前["修正次数"] < 1:
        return {"通过": False, "说明": "缺少步骤一的已修正窗，请按顺序跑演练"}

    版本前 = 前["版本"]
    合计前 = dict(前["当前合计"])
    首跳旧值 = 前["撤回链"][0]["旧点赞"]

    装载.装一批(
        {
            "批次编号": f"{房}-迟到2-{_运行号()}",
            "事件": [_事件(f"{房}-L2", 房, "2026-11-22T12:00:50Z", 7, 20, "送礼")],
        }
    )
    后 = _取证据(wk)
    版本升 = 后["版本"] == 版本前 + 1
    两跳 = 后["修正次数"] == 2 and len(后["历史合计"]) == 3
    链衔接 = not 后["链问题"]
    首跳旧值仍可查 = 后["撤回链"][0]["旧点赞"] == 首跳旧值
    当前合计对 = (
        后["当前合计"]["点赞"] == 合计前["点赞"] + 7
        and 后["当前合计"]["送礼"] == 合计前["送礼"] + 20
        and 后["当前合计"]["笔数"] == 合计前["笔数"] + 1
    )
    通过 = all([版本升, 两跳, 链衔接, 首跳旧值仍可查, 当前合计对])
    return {
        "通过": 通过,
        "房间": 房,
        "窗键": wk,
        "版本前": 版本前,
        "版本后": 后["版本"],
        "版本升高": 版本升,
        "修正次数": 后["修正次数"],
        "撤回链": 后["撤回链"],
        "历史合计三档": 后["历史合计"],
        "首跳旧值仍可查": 首跳旧值仍可查,
        "链衔接": 链衔接,
        "说明": [
            f"甲口径：窗表只留当前合计（版本 {版本前}→{后['版本']}，修正 {后['修正次数']} 次）",
            "历史旧合计经撤回链两跳仍可回溯："
            + " → ".join(
                f"v{点['版本']}赞{点['点赞']}/送{点['送礼']}" for 点 in 后["历史合计"]
            ),
        ]
        if 通过
        else ["第二次迟到修正的版本或撤回链不符合预期"],
    }


def _并发批次(房: str, 前缀: str, 事件们: list, 轮次: int) -> dict:
    return 装载.装一批({"批次编号": f"{房}-{前缀}-{轮次}-{_运行号()}", "事件": 事件们})


def _扫半截(conn, 房间键: str = "") -> list:
    半截 = []
    sql = "SELECT * FROM 热度窗"
    参 = []
    if 房间键:
        sql += " WHERE 房间键=?"
        参.append(房间键)
    for 窗行 in conn.execute(sql, 参).fetchall():
        if 窗行["状态"] != "已关闭":
            continue
        撤数 = conn.execute(
            "SELECT COUNT(*) FROM 撤回单 WHERE 窗键=?", (窗行["窗键"],)
        ).fetchone()[0]
        if int(窗行["版本"]) != 1 + 撤数:
            半截.append(f"窗{窗行['窗键']}版本{窗行['版本']}≠1+撤回数{撤数}")
        末 = conn.execute(
            "SELECT * FROM 撤回单 WHERE 窗键=? ORDER BY 编号 DESC LIMIT 1",
            (窗行["窗键"],),
        ).fetchone()
        if 末 and (
            末["新点赞"] != 窗行["点赞合计"]
            or 末["新送礼"] != 窗行["送礼合计"]
            or 末["新笔数"] != 窗行["事件笔数"]
        ):
            半截.append(f"窗{窗行['窗键']}末次撤回新值未落到窗行")
        证据 = 允许迟到策略._组装证据(conn, 窗行)
        if 证据["链问题"]:
            半截.append(f"窗{窗行['窗键']}证据链问题:{'；'.join(证据['链问题'])}")
    return 半截


def _步骤三(轮数: int = 6) -> dict:
    """每轮独立房间：A 迟到修正、B 抬水位（停在旁路界内）、C 越界扫描三方并发。

    C 可能抢在 A 之前把水位推过旁路界（此时迟到事件应转旁路，不得修窗），
    也可能落在 A 之后。两种交错都必须事后不出现「撤回单已落、窗行未动」。
    """
    轮报告 = []
    for 轮 in range(1, 轮数 + 1):
        房 = f"{演练房_并发}{轮}"
        _重置房(房)
        wk = 时间.窗键(房, 首窗起)

        _并发批次(
            房,
            "打底",
            [
                _事件(f"{房}-B1", 房, "2026-11-22T12:00:10Z", 1),
                _事件(f"{房}-B2", 房, "2026-11-22T12:01:05Z", 1),
            ],
            0,
        )

        迟到们 = [
            _事件(f"{房}-R{轮}-A{i}", 房, f"2026-11-22T12:00:{20 + i * 3:02d}Z", 1)
            for i in range(4)
        ]
        抬水们 = [
            _事件(f"{房}-R{轮}-B{i}", 房, f"2026-11-22T12:01:{10 + i:02d}Z", 1)
            for i in range(3)
        ]
        越界们 = [_事件(f"{房}-R{轮}-C", 房, "2026-11-22T12:01:40Z", 1)]

        with concurrent.futures.ThreadPoolExecutor(max_workers=3) as 池:
            if 轮 % 2 == 0:
                顺序 = [("C越界", 越界们), ("B抬水", 抬水们), ("A迟到", 迟到们)]
            else:
                顺序 = [("A迟到", 迟到们), ("B抬水", 抬水们), ("C越界", 越界们)]
            任务 = [池.submit(_并发批次, 房, 名, 事, 轮) for 名, 事 in 顺序]
            结果 = [t.result() for t in 任务]

        with 读事务() as conn:
            本房半截 = _扫半截(conn, 房)
            窗行 = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (wk,)).fetchone()
            首窗版本 = 窗行["版本"] if 窗行 else None
            首窗合计 = dict(窗行) if 窗行 else None
        证 = _取证据(wk)
        轮报告.append(
            {
                "轮": 轮,
                "房间": 房,
                "本批撤回": sum(r["撤回"] for r in 结果),
                "本批旁路": sum(r["旁路"] for r in 结果),
                "首窗版本": 首窗版本,
                "首窗修正次数": 证["修正次数"] if 证 else None,
                "首窗合计": 证["当前合计"] if 证 else None,
                "半截检出": 本房半截,
            }
        )

    全部半截 = [x for r in 轮报告 for x in r["半截检出"]]
    有修正轮 = [r for r in 轮报告 if (r["本批撤回"] or 0) > 0]
    有旁路轮 = [r for r in 轮报告 if (r["本批旁路"] or 0) > 0]
    return {
        "通过": not 全部半截 and bool(有修正轮),
        "窗键样例": f"{演练房_并发}1|{首窗起}",
        "轮数": 轮数,
        "总撤回": sum(r["本批撤回"] for r in 轮报告),
        "总旁路": sum(r["本批旁路"] for r in 轮报告),
        "有修正轮数": len(有修正轮),
        "有旁路轮数": len(有旁路轮),
        "轮报告": 轮报告,
        "半截检出": 全部半截,
        "说明": "并发交错下每笔撤回都伴随窗行改动与版本跃迁，未出现「撤回已写而窗未改」"
        if not 全部半截
        else "；".join(全部半截)[:600],
    }


def _附加_故障注入同成败() -> dict:
    """在「改窗合计」与「写撤回单」之间注入异常，验证整事务回滚、两处都不留痕。"""
    房 = "房丁"
    _重置房(房)
    wk = 时间.窗键(房, 首窗起)
    _并发批次(
        房,
        "打底",
        [
            _事件(f"{房}-B1", 房, "2026-11-22T12:00:10Z", 2),
            _事件(f"{房}-B2", 房, "2026-11-22T12:01:05Z", 2),
        ],
        0,
    )
    前 = _取证据(wk)
    if 前 is None:
        return {"通过": False, "说明": "打底关窗失败"}

    注入 = {"已触发": False}

    def 提交前炸(窗键: str) -> None:
        注入["已触发"] = True
        raise RuntimeError("注入：撤回单落库后、提交前失败")

    异常 = None
    try:
        装载.装一批(
            {
                "批次编号": f"{房}-注入-{_运行号()}",
                "事件": [_事件(f"{房}-X1", 房, "2026-11-22T12:00:55Z", 9)],
            },
            修正提交前钩子=提交前炸,
        )
    except Exception as e:
        异常 = f"{type(e).__name__}: {e}"

    后 = _取证据(wk)
    窗行未动 = 后["当前合计"] == 前["当前合计"] and 后["版本"] == 前["版本"]
    无撤回 = 后["修正次数"] == 0
    无事件 = 后 is not None and _事件计数(房, f"{房}-X1") == 0
    水位未抬 = 后["水位"] == 前["水位"]
    通过 = bool(注入["已触发"] and 异常 and 窗行未动 and 无撤回 and 无事件 and 水位未抬)
    return {
        "通过": 通过,
        "房间": 房,
        "窗键": wk,
        "注入已触发": 注入["已触发"],
        "异常": 异常,
        "窗行未动": 窗行未动,
        "撤回单未留": 无撤回,
        "事件未落": 无事件,
        "水位回滚": 水位未抬,
        "说明": "撤回单与窗行同事务：中途失败整批回滚，不存在半截"
        if 通过
        else "故障注入后仍留下痕迹，原子性不足",
    }


def _事件计数(房间键: str, 事件编号: str) -> int:
    with 读事务() as conn:
        return conn.execute(
            "SELECT COUNT(*) FROM 互动事件 WHERE 房间键=? AND 事件编号=?",
            (房间键, 事件编号),
        ).fetchone()[0]
