from app.db import 读事务
from app.services import 时间
from app.modules import 撤回摘要

状态 = "已实现"

口径 = "甲-原地改窗合计并写撤回单·撤回摘要链续写接管二次修正"
证据类型 = "撤回单链+撤回摘要链"


class 修正违例(Exception):
    """修正前置条件被打破：调用方据此整批回滚。"""


def 允许迟到界(窗止事件时: str, 允许迟到秒: int) -> str:
    return 时间.加秒(窗止事件时, int(允许迟到秒))


def 可修正(水位事件时: str, 窗止事件时: str, 允许迟到秒: int) -> bool:
    """水位尚未越过「窗止 + 允许迟到」→ 该窗仍可接受迟到修正。"""
    return 时间.解析(水位事件时) < 时间.解析(允许迟到界(窗止事件时, 允许迟到秒))


def 修正已关闭窗(
    conn,
    *,
    窗,
    事件编号: str,
    点赞: int,
    送礼: int,
    处理时: str,
    批次编号: str = "",
    提交前钩子=None,
) -> dict:
    """在写事务内原地修正已关闭窗并留下撤回证据。

    调用方必须已保证：窗状态为已关闭、水位未越过允许迟到界。
    这里再做一次硬校验，并用版本号做乐观并发保护。

    摘要接管（甲口径·摘要链续写）：
    - 首撤：起点取关闭发射值（窗表现行），撤回单与摘要链第一跳同票落库；
    - 二撤起：起点必须取摘要链末跳的新合计并升链序号续写，
      缺摘要、链断、哈希与撤回单对不上、窗行被绕开摘要改歪，一律违例；
    改窗、撤回单、摘要同属一个事务，任一步失败整批回滚，
    杜绝「首撤成功摘要空」「二次路径绕开摘要改窗」。

    提交前钩子仅供演练注入故障（验证「撤回已落但未提交」也会整批回滚），
    生产调用不传。
    """
    if 窗["状态"] != "已关闭":
        raise 修正违例(f"窗{窗['窗键']}未关闭，不允许走迟到修正")

    窗键 = 窗["窗键"]
    撤回跳数 = conn.execute(
        "SELECT COUNT(*) FROM 撤回单 WHERE 窗键=?", (窗键,)
    ).fetchone()[0]
    if 撤回跳数 == 0:
        # 首撤：起点 = 关闭发射值（窗表现行）
        旧赞 = int(窗["点赞合计"])
        旧送 = int(窗["送礼合计"])
        旧笔 = int(窗["事件笔数"])
        链序号 = 1
    else:
        # 二撤起：摘要接管——以摘要链末跳新合计为起点续写，缺摘要或链断整票失败
        try:
            起点 = 撤回摘要.续写起点(conn, 窗)
        except 撤回摘要.摘要违例 as e:
            raise 修正违例(str(e))
        旧赞 = 起点["点赞"]
        旧送 = 起点["送礼"]
        旧笔 = 起点["笔数"]
        链序号 = 起点["链序号"]

    旧版 = int(窗["版本"])
    新赞 = 旧赞 + int(点赞)
    新送 = 旧送 + int(送礼)
    新笔 = 旧笔 + 1
    新版本 = 旧版 + 1

    游标 = conn.execute(
        """UPDATE 热度窗
              SET 点赞合计=?, 送礼合计=?, 事件笔数=?, 版本=?
            WHERE 窗键=? AND 状态='已关闭' AND 版本=?""",
        (新赞, 新送, 新笔, 新版本, 窗键, 旧版),
    )
    if 游标.rowcount != 1:
        raise 修正违例(f"窗{窗键}修正并发冲突：版本/状态已变")

    游标 = conn.execute(
        """INSERT INTO 撤回单(
               窗键,房间键,原因,旧点赞,新点赞,旧送礼,新送礼,
               旧笔数,新笔数,旧版本,新版本,处理时,事件编号,批次编号)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
        (
            窗键, 窗["房间键"], "迟到修正",
            旧赞, 新赞, 旧送, 新送,
            旧笔, 新笔, 旧版, 新版本,
            处理时, 事件编号, 批次编号,
        ),
    )
    if 游标.rowcount != 1:
        raise 修正违例(f"窗{窗键}撤回单未落，整批回滚")
    撤回单号 = 游标.lastrowid

    # 同票落摘要：窗键、事件编号、旧→新合计、摘要哈希、链序号；
    # 摘要写失败与撤回单同命运——整批回滚，禁止「首撤成功摘要空」。
    try:
        摘要哈希 = 撤回摘要.写摘要(
            conn,
            窗键=窗键,
            事件编号=事件编号,
            旧合计=撤回摘要.合计串(旧赞, 旧送, 旧笔),
            新合计=撤回摘要.合计串(新赞, 新送, 新笔),
            链序号=链序号,
            撤回单号=撤回单号,
            批号=批次编号,
            时刻=处理时,
        )
    except 撤回摘要.摘要违例 as e:
        raise 修正违例(str(e))

    if 提交前钩子 is not None:
        提交前钩子(窗键)

    return {
        "窗键": 窗键,
        "旧版本": 旧版,
        "新版本": 新版本,
        "旧点赞": 旧赞,
        "新点赞": 新赞,
        "旧送礼": 旧送,
        "新送礼": 新送,
        "旧笔数": 旧笔,
        "新笔数": 新笔,
        "链序号": 链序号,
        "摘要哈希": 摘要哈希,
        "证据类型": 证据类型,
    }


def _撤回链(conn, 窗键: str) -> list:
    rows = conn.execute(
        "SELECT * FROM 撤回单 WHERE 窗键=? ORDER BY 编号", (窗键,)
    ).fetchall()
    return [dict(r) for r in rows]


def _组装证据(conn, 窗) -> dict:
    房间键 = 窗["房间键"]
    水位行 = conn.execute("SELECT * FROM 水位线 WHERE 房间键=?", (房间键,)).fetchone()
    水位 = 水位行["事件时水位"] if 水位行 else ""
    允许迟到 = int(水位行["允许迟到秒"]) if 水位行 else 0
    界 = 允许迟到界(窗["窗止事件时"], 允许迟到)

    链 = _撤回链(conn, 窗["窗键"])
    窗版本 = int(窗["版本"])
    基础版本 = 窗版本 - len(链)

    历史合计 = [
        {
            "版本": max(基础版本, 0),
            "点赞": 链[0]["旧点赞"] if 链 else int(窗["点赞合计"]),
            "送礼": 链[0]["旧送礼"] if 链 else int(窗["送礼合计"]),
            "笔数": 链[0]["旧笔数"] if 链 else int(窗["事件笔数"]),
            "来源": "关闭发射值",
        }
    ] if 链 else [
        {
            "版本": 窗版本,
            "点赞": int(窗["点赞合计"]),
            "送礼": int(窗["送礼合计"]),
            "笔数": int(窗["事件笔数"]),
            "来源": "关闭发射值",
        }
    ]

    链问题 = []
    if 链:
        期望版本 = 链[0]["旧版本"]
        if 期望版本 < 1:
            链问题.append(f"首个撤回旧版本异常:{期望版本}")
        for 跳 in 链:
            if 跳["旧版本"] != 期望版本:
                链问题.append(f"撤回{跳['编号']}版本链断裂：旧{跳['旧版本']}≠期望{期望版本}")
            if 跳["新版本"] != 跳["旧版本"] + 1:
                链问题.append(f"撤回{跳['编号']}版本未逐跳+1")
            if 跳["新笔数"] != 跳["旧笔数"] + 1:
                链问题.append(f"撤回{跳['编号']}笔数未逐跳+1")
            if 历史合计[-1]["点赞"] != 跳["旧点赞"] or 历史合计[-1]["送礼"] != 跳["旧送礼"]:
                链问题.append(f"撤回{跳['编号']}旧值与上一跳新值不衔接")
            历史合计.append(
                {
                    "版本": 跳["新版本"],
                    "点赞": 跳["新点赞"],
                    "送礼": 跳["新送礼"],
                    "笔数": 跳["新笔数"],
                    "来源": f"撤回{跳['编号']}",
                    "触发事件": 跳["事件编号"],
                }
            )
            期望版本 = 跳["新版本"]
        if 链[-1]["新点赞"] != int(窗["点赞合计"]) or 链[-1]["新送礼"] != int(窗["送礼合计"]):
            链问题.append("末次撤回新值与窗表现行合计不一致")
        if 链[-1]["新笔数"] != int(窗["事件笔数"]):
            链问题.append("末次撤回新笔数与窗表现行笔数不一致")
        if 链[-1]["新版本"] != 窗版本:
            链问题.append(f"末次撤回新版本{链[-1]['新版本']}≠窗表版本{窗版本}")

    agg = conn.execute(
        """SELECT COALESCE(SUM(点赞增量),0) AS 赞, COALESCE(SUM(送礼额),0) AS 送, COUNT(*) AS n
             FROM 互动事件 WHERE 窗键=? AND 命运='已入窗'""",
        (窗["窗键"],),
    ).fetchone()
    if int(agg["赞"]) != int(窗["点赞合计"]) or int(agg["送"]) != int(窗["送礼合计"]):
        链问题.append(
            f"窗表合计与窗内事件合计不符：窗赞{窗['点赞合计']}/送{窗['送礼合计']} vs 事件赞{agg['赞']}/送{agg['送']}"
        )
    if int(agg["n"]) != int(窗["事件笔数"]):
        链问题.append(f"窗表笔数{窗['事件笔数']}≠窗内事件{agg['n']}")

    # 摘要链 ↔ 撤回单 ↔ 窗行三面对账：撤回在摘要空、链断、哈希对不上、
    # 末跳≠窗行（窗被绕开摘要改歪）都计入链问题，证据即 invalid。
    摘要对账 = 撤回摘要.对账窗(conn, 窗)
    链问题.extend(摘要对账["问题"])

    关闭版本 = 基础版本 if 链 else 窗版本
    if 窗["状态"] == "已关闭" and 关闭版本 < 1 and not 链问题:
        链问题.append("已关闭窗版本未起步")

    return {
        "窗键": 窗["窗键"],
        "房间键": 房间键,
        "窗起事件时": 窗["窗起事件时"],
        "窗止事件时": 窗["窗止事件时"],
        "状态": 窗["状态"],
        "允许迟到秒": 允许迟到,
        "允许迟到界": 界,
        "水位": 水位,
        "可再修正": 窗["状态"] == "已关闭" and bool(水位) and 可修正(水位, 窗["窗止事件时"], 允许迟到),
        "口径": 口径,
        "证据类型": 证据类型,
        "版本": 窗版本,
        "基础版本": 关闭版本,
        "修正次数": len(链),
        "当前合计": {
            "点赞": int(窗["点赞合计"]),
            "送礼": int(窗["送礼合计"]),
            "笔数": int(窗["事件笔数"]),
        },
        "撤回链": 链,
        "历史合计": 历史合计,
        "摘要链": 摘要对账["摘要链"],
        "摘要根数": 摘要对账["根数"],
        "摘要钉死": 摘要对账["钉死"],
        "历史旧值可查": bool(链),
        "历史旧值查询方式": "窗表只存当前合计；历史旧合计经撤回单旧值→新值链逐跳回溯",
        "链问题": 链问题,
        "valid": bool(窗["状态"] == "已关闭" and not 链问题),
        "说明": (
            "关闭窗的迟到修正在允许迟到界内完成，窗表合计已原地抬升且撤回链完整"
            if 窗["状态"] == "已关闭" and not 链问题
            else ("窗仍开启，尚未发射" if 窗["状态"] != "已关闭" else "；".join(链问题))
        ),
    }


def 窗口证据(窗键: str):
    with 读事务() as conn:
        窗 = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (窗键,)).fetchone()
        if not 窗:
            return None
        return _组装证据(conn, 窗)


def 列窗口证据(房间键: str = "", 状态: str = "已关闭") -> list:
    with 读事务() as conn:
        sql = "SELECT * FROM 热度窗 WHERE 1=1"
        参 = []
        if 房间键:
            sql += " AND 房间键=?"
            参.append(房间键)
        if 状态:
            sql += " AND 状态=?"
            参.append(状态)
        sql += " ORDER BY 窗起事件时 DESC"
        return [_组装证据(conn, 窗) for 窗 in conn.execute(sql, 参).fetchall()]


def 汇总(证据: dict) -> dict:
    return {
        "窗键": 证据["窗键"],
        "房间键": 证据["房间键"],
        "允许迟到界": 证据["允许迟到界"],
        "水位": 证据["水位"],
        "版本": 证据["版本"],
        "修正次数": 证据["修正次数"],
        "当前合计": 证据["当前合计"],
        "摘要根数": 证据["摘要根数"],
        "摘要钉死": 证据["摘要钉死"],
        "valid": 证据["valid"],
    }
